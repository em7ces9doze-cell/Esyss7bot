function slugify(value) {
  const raw = String(value || "em7-bot");
  const s = raw.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 30);
  return SAFE_ID.test(s) ? s : `em7-${crypto.createHash("sha1").update(raw).digest("hex").slice(0, 6)}`;
}
function safeText(value, max, fallback = "") {
  return String(value ?? fallback).replace(/[\u0000-\u001f]/g, " ").trim().slice(0, max);
}
function safeColor(value) {
  const v = String(value || "5865F2").replace(/^#/, "");
  if (!/^[0-9a-fA-F]{6}$/.test(v)) throw new Error("اللون يجب أن يكون HEX من 6 خانات، مثال 5865F2.");
  return v.toUpperCase();
}
