function sourceFor(type, config) {
  if (type === "ticket") return ticketSource(config);
  if (type === "events") return eventsSource(config);
  if (type === "welcome") return welcomeSource(config);
  throw new Error("نوع البوت غير مدعوم. الأنواع الحالية: ticket, events, welcome.");
}
async function zipDirectory(dir, outPath) {
  const archiver = require("archiver");
  await new Promise((resolve,reject)=>{
    const output=require("node:fs").createWriteStream(outPath);
    const archive=archiver("zip",{zlib:{level:9}});
    output.on("close",resolve);archive.on("error",reject);archive.pipe(output);archive.directory(dir,false);archive.finalize();
  });
}
async function buildProject({type,name,config={},description=""}) {
  if (!DEFAULTS[type]) throw new Error("النوع غير مدعوم.");
  const projectName=slugify(name);const dir=path.join(ROOT,projectName);
  await fs.mkdir(dir,{recursive:true});
  const merged={...DEFAULTS[type],...config};merged.color=safeColor(merged.color);
  for(const key of Object.keys(merged)) if(typeof merged[key]==="string") merged[key]=safeText(merged[key], key.toLowerCase().includes("description")?900:180);
  const manifest={name:projectName,type,description:safeText(description,500),config:merged,updatedAt:new Date().toISOString(),factoryVersion:"1.0.0"};
  await fs.writeFile(path.join(dir,"index.js"),sourceFor(type,merged),"utf8");
  await fs.writeFile(path.join(dir,"package.json"),json(packageJson(projectName)),"utf8");
  await fs.writeFile(path.join(dir,".env.example"),envExample(),"utf8");
  await fs.writeFile(path.join(dir,"README.md"),readme(projectName,type),"utf8");
  await fs.writeFile(path.join(dir,"em7-project.json"),json(manifest),"utf8");
  const zipPath=path.join(ROOT,`${projectName}.zip`);await zipDirectory(dir,zipPath);
  return {projectName,type,dir,zipPath,config:merged,updatedAt:manifest.updatedAt};
}
async function createBotProject(args){return buildProject(args);}
async function updateBotProject({name,config={},description=""}){
  const projectName=slugify(name);const dir=path.join(ROOT,projectName);
  let previous;try{previous=JSON.parse(await fs.readFile(path.join(dir,"em7-project.json"),"utf8"));}catch{throw new Error("لم أجد مشروعاً بهذا الاسم. أنشئ المشروع أولاً.");}
  return buildProject({type:previous.type,name:projectName,config:{...previous.config,...config},description:description||previous.description});
}
